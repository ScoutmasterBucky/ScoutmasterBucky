#!/usr/bin/env node
// Make small thumbnails of every hard cover photo in the filestore for the hard
// cover type pages, and write the list of them to
// src/data/merit-badge-history/hardcover-photos.yaml.
//
//   node prepare-hardcover-thumbs.mjs [filestore pamphlet folder]
import { readdir, mkdir, writeFile, stat } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const source = process.argv[2] ?? 'C:/filestore/history/merit-badge-pamphlets';
// Served by filestore.scoutmasterbucky.com, not kept in git (history-tools/web-photos.mjs)
const outDir = 'C:/filestore/history/web/hardcovers';
const height = 300;

const found = {};
for (const slug of (await readdir(source)).sort()) {
    const folder = path.join(source, slug);
    if (!(await stat(folder)).isDirectory()) continue;

    for (const file of (await readdir(folder)).sort()) {
        // e.g. archery-hcj.jpg, camping-hcp2.jpg, art-hcjv1.jpg, rowing-hc-misc-k.jpg
        const match = file.match(/-(hc[a-z]+|hc-misc-[a-z]+)(\d*)(v\d)?\.jpg$/i);
        if (!match) continue;

        let type = match[1].toUpperCase();
        let variant = `${match[2]}${match[3] ?? ''}`;
        // The odd one-off covers (HCLM, HCLX, HCQQ and the hc-misc files) share
        // one Misc page; the variant keeps the cover's own code
        if (/^HC-MISC-|^HC(LM|LX|QQ)$/.test(type)) {
            variant = type.startsWith('HC-MISC-') ? `Misc ${type.slice(8)}${variant}` : `${type}${variant}`;
            type = 'MISC';
        }
        const name = file.toLowerCase().replace(/\.jpg$/, '.webp');
        await mkdir(path.join(outDir, type.toLowerCase()), { recursive: true });
        await sharp(path.join(folder, file))
            .resize({ height, withoutEnlargement: true })
            .webp({ quality: 80 })
            .toFile(path.join(outDir, type.toLowerCase(), name));

        (found[type] ??= []).push({ slug, variant, image: `/history/hardcovers/${type.toLowerCase()}/${name}` });
    }
}

const yaml = Object.keys(found)
    .sort()
    .map(type =>
        [`${type}:`, ...found[type].map(p => `    - { slug: ${p.slug}${p.variant ? `, variant: '${p.variant}'` : ''}, image: ${p.image} }`)].join('\n')
    )
    .join('\n');
await writeFile(
    'src/data/merit-badge-history/hardcover-photos.yaml',
    `# Generated by prepare-hardcover-thumbs.mjs from the filestore; do not edit by hand.\n${yaml}\n`
);

console.log(Object.entries(found).map(([t, list]) => `${t}: ${list.length}`).join(', '));
